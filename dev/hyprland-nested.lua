-- Nested Hyprland session for developing Dynamic-Larpland. Started by scripts/dev.sh;
-- runs as a window inside the host compositor, so the host shell (e.g. Noctalia) is untouched.
-- SUPER combos are grabbed by the host, so this session uses ALT as its modifier.
local repo = os.getenv("DYNAMIC_LARPLAND_REPO")
local dev = repo .. "/.dev"
local mod = "ALT"

hl.monitor({ output = "", mode = "preferred", position = "auto", scale = 1 })

hl.config({
    input = {
        kb_layout = "us,ru",
        kb_options = "grp:alt_shift_toggle",
        follow_mouse = 1,
    },
    general = {
        gaps_in = 4,
        gaps_out = 8,
    },
    misc = {
        disable_hyprland_logo = true,
        disable_splash_rendering = true,
    },
})

hl.on("hyprland.start", function()
    hl.exec_cmd("qs -p " .. repo .. "/dev/wallpaper")
    -- Host players aren't visible on this session's own D-Bus, so start a demo one.
    hl.exec_cmd("env XDG_STATE_HOME=" .. dev .. "/state python3 " .. repo .. "/dev/fake-player.py")
    -- The island keeps its config/state under .dev so the real ~/.config is never touched.
    hl.exec_cmd("env XDG_CONFIG_HOME=" .. dev .. "/config XDG_STATE_HOME=" .. dev .. "/state "
        .. repo .. "/scripts/run.sh")
end)

hl.bind(mod .. " + Return", hl.dsp.exec_cmd("kitty"))
hl.bind(mod .. " + Q", hl.dsp.window.close())
hl.bind(mod .. " + SHIFT + E", hl.dsp.exit())
hl.bind(mod .. " + N", hl.dsp.exec_cmd("notify-send -a Dev 'Test notification' 'Sent from the nested session'"))

-- Island keybinds generated by its settings page (defaults set by scripts/dev.sh: ALT + Space = launcher).
pcall(dofile, dev .. "/config/dynamic-larpland/binds.lua")

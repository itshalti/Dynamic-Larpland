#include "compositors/hyprland.h"
#include "config/config.h"
#include "core/log.h"
#include "system/process.h"
#include "util/file_utils.h"

#include <filesystem>
#include <fstream>
#include <sstream>

namespace keybinds {

  namespace {

    constexpr Logger kLog("keybinds");

    std::string selfPath() {
      std::error_code ec;
      return std::filesystem::read_symlink("/proc/self/exe", ec).string();
    }

    std::string luaString(const std::string& s) {
      std::string out = "\"";
      for (const char c : s) {
        if (c == '"' || c == '\\') {
          out += '\\';
        }
        out += c;
      }
      return out + "\"";
    }

  } // namespace

  std::string bindsPath() { return FileUtils::configDir() + "/binds.lua"; }

  std::string includeLine() { return "pcall(dofile, " + luaString(bindsPath()) + ")"; }

  std::string ipcCommand(const std::string& action) { return selfPath() + " msg " + action; }

  void writeHyprland(const Config& config) {
    if (!HyprlandService::available()) {
      return;
    }
    std::string lua = "-- Generated by Dynamic-Larpland settings. Edit the keybinds there, not here.\n";
    for (const char* action : kActions) {
      const auto it = config.keybinds.find(action);
      if (it != config.keybinds.end() && !it->second.empty()) {
        lua += "hl.bind(" + luaString(it->second) + ", hl.dsp.exec_cmd(" + luaString(ipcCommand(action)) + "))\n";
      }
    }
    std::stringstream current;
    current << std::ifstream(bindsPath()).rdbuf();
    if (current.str() == lua) {
      return;
    }
    std::ofstream(bindsPath(), std::ios::trunc) << lua;
    kLog.info("wrote {}", bindsPath());
    if (!process::runAsync({"hyprctl", "reload", "config-only"})) {
      kLog.warn("could not run hyprctl reload");
    }
  }

} // namespace keybinds
